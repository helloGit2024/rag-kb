-- ─────────────────────────────────────────────────────────────────────
-- 报销表
-- 部门：101 研发部 / 102 销售部 / 103 行政部
-- 类别：TRAIN 培训费 / TRAVEL 差旅费 / OFFICE 办公费 / ENT 招待费 / OTHER 其他
-- 状态：PENDING 待审批 / APPROVED 已通过 / REJECTED 已驳回 / VOID 已作废
--
-- ★ 数据是刻意设计的，每一行都对应一个"口径陷阱"或"边界情况"：
--   E012 8 月提交 / 9 月结算   →  按提交日算会漏掉它（口径题）
--   E013 9 月提交 / 10 月结算  →  按提交日算会把它错算进 9 月（口径题）
--   E022 REJECTED 但有结算日   →  不过滤 status 会多算 3500（口径题）
--   E017 VOID 且有金额         →  作废单不能计入
--   E004 PENDING 未结算        →  待审批单不计入任何月份
--   E018/E019 10 月数据        →  "上个月"不能把它算进来
--   E021 2025-09 数据          →  去年同月，时间范围写错就会算进来
-- ─────────────────────────────────────────────────────────────────────
CREATE TABLE expense_claims (
    id          text   PRIMARY KEY,
    dept_id     bigint NOT NULL,
    employee_id bigint NOT NULL,
    amount      numeric(12,2) NOT NULL,
    category    text   NOT NULL,
    status      text   NOT NULL,
    submit_date date   NOT NULL,
    settle_date date            -- 未结算时为空（E004）
);

