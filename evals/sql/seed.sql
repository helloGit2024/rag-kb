-- 口径：settle_date 归属月份 + status='APPROVED'
-- ═══════════════════════════════════════════════════════════════════════
--
-- 【2026-09 · 培训支出 = SUM(amount) WHERE category='TRAIN' AND status='APPROVED' AND settle_date∈9月】
--   101 研发部：E001 12000 + E002 8000 + E003 5000                    = 25,000（3 笔）
--   102 销售部：E008 20000 + E009 6000 + E012 9000                    = 35,000（3 笔）
--   103 行政部：E015 2500                                             =  2,500（1 笔）
--   ─────────────────────────────────────────────────────────────────
--   合计                                                              = 62,500（7 笔）
--
--   ★ 错误口径会得到的数字（都可执行成功、都不是"报错"）：
--     按 submit_date：E001+E002+E003+E008+E009+E013+E015
--                     = 12000+8000+5000+20000+6000+7000+2500     = 60,500（7 笔）
--     不过滤 status：62,500 + E022 3500                          = 66,000（8 笔）
--     时间范围写错（把 2025-09 也算进来）：62,500 + E021 10000     = 72,500（8 笔）
--
-- 【2026-09 · 差旅支出】E006 1500 + E010 4500 + E016 1800                =  7,800（3 笔）
-- 【2026-09 · 已通过报销单数（全部类别）】
--   101: E001 E002 E003 E006 E007 = 5 笔（合计 27,300）
--   102: E008 E009 E010 E011 E012 = 5 笔（合计 40,700）
--   103: E015 E016                = 2 笔（合计  4,300）
--   合计 12 笔 / 72,300            → AVG = 6,025.00
-- 【2025-09 · 培训支出】E021                                            = 10,000（1 笔）
-- 【2026-10 · 培训支出】E013 7000 + E018 9000 + E019 11000              = 28,000（3 笔）
