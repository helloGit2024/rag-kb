-- SQL 通道评估的固定种子数据集（seed.sql）
-- ═══════════════════════════════════════════════════════════════════════
-- 为什么必须有这份文件：
--   结果集比对的前提是"数据不变"。业务库是活的（今天有人提交报销单），
--   所以不能对着生产库跑评估 —— 否则你会得到"今天 100 分、明天 60 分"，
--   而你会以为是模型不稳定。
--
-- 跑评估的方式：建临时库 → 灌本文件 → 跑全量题目 → 销毁。
--   每次评估都从同一个种子开始，数字才可比。
--
-- 附加价值：这份数据是**为了测出"口径错"而设计的**。
--   生产数据里"跨月结算""已驳回但有结算日""去年同月"这类边界数据太少，
--   而在标准数据集里可以人为造出来 —— 这是唯一能检测"口径猜错"的手段。
--
-- ⚠️ 这是一份示例。换成真实数据源时，字段名与表名要跟着换，
--    并同步更新 config/semantic_layer.yaml。
-- ═══════════════════════════════════════════════════════════════════════

-- 时间基准：评估时把"今天"冻结为 2026-10-15（见 golden_set_sql.yaml 的 frozen_now）。
-- 所有"上个月/本月/本季度"都相对这个日期解析。
-- ★ 不冻结"今天"的话，这份题库会随时间自然腐烂（下个月跑，"上个月"就变成了 10 月）。

DROP TABLE IF EXISTS expense_claims;
DROP TABLE IF EXISTS employees;

-- ─────────────────────────────────────────────────────────────────────
-- 员工表
-- 注意：id_card / bank_account / phone / salary 在语义层里是 denylisted_columns
--      （存在但不可查询），用于测试"敏感列必须被拦下"。
-- ─────────────────────────────────────────────────────────────────────
CREATE TABLE employees (
    id           bigint PRIMARY KEY,
    name         text   NOT NULL,
    dept_id      bigint NOT NULL,
    hire_date    date   NOT NULL,
    job_level    text   NOT NULL,
    status       text   NOT NULL,
    -- 以下四列**故意存在但禁止查询**（`config/semantic_layer.yaml` → denylisted_columns）
    id_card      text,
    bank_account text,
    phone        text,
    salary       numeric(12,2)
);

